RATE_VERSIONS = ["silent", "placebo", "explicit", "implied", "buried", "chain"]
PROPOSE_VERSIONS = ["silent", "explicit", "buried", "chain"]


def docs(s, v):
    entry, memo = s["base"], s["memo"]
    if v in ("placebo", "explicit", "implied"):
        entry += " " + s[v]
    elif v == "buried":
        entry = " ".join([s["base"]] + s["filler"][:3] + [s["implied"]] + s["filler"][3:])
    elif v == "chain":
        entry += " " + s["link1"]
        memo += " " + s["link2"]
    return entry, memo


def rate_prompt(s, v):
    entry, memo = docs(s, v)
    return (f"{s['study']}\n\nProposed instrument: {s['instrument']}\n\nCodebook entry:\n{entry}\n\n{memo}\n\n"
            "Is this a valid instrument for this study? Reason briefly, in at most four sentences, then end with exactly two lines:\n"
            "RATING: <0-100, your probability that the instrument is valid>\nDECISION: ACCEPT or REJECT")


def propose_prompt(s, v):
    entry, memo = docs(s, v)
    book = "\n".join(s["others"][:3] + [entry] + s["others"][3:])
    return (f"{s['study']}\n\nThe researcher has the following codebook:\n{book}\n\n{memo}\n\n"
            "Which variable in this codebook, if any, should the researcher use as an instrument for the treatment? "
            "Reason briefly, in at most four sentences, then end with exactly one line:\n"
            "INSTRUMENT: <variable name, or NONE>")


def alt_prompt(s, v):
    entry, memo = docs(s, v)
    book = "\n".join(s["others"][:2] + [s["alt"]] + s["others"][2:4] + [entry] + s["others"][4:])
    return (f"{s['study']}\n\nThe researcher has the following codebook:\n{book}\n\n{memo}\n\n"
            "Which variable in this codebook, if any, should the researcher use as an instrument for the treatment? "
            "Reason briefly, in at most four sentences, then end with exactly one line:\n"
            "INSTRUMENT: <variable name, or NONE>")


def ask(text):
    if BACKEND == "ollama":
        import urllib.request
        body = json.dumps({"model": MODEL, "prompt": text, "stream": False, "options": {"temperature": 1.0, "num_ctx": 4096}}).encode()
        req = urllib.request.Request("http://localhost:11434/api/generate", body, {"Content-Type": "application/json"})
        return json.loads(urllib.request.urlopen(req, timeout=600).read())["response"]
    if BACKEND == "openrouter":
        from openai import OpenAI
        c = OpenAI(base_url="https://openrouter.ai/api/v1", api_key=os.environ["OPENROUTER_API_KEY"], timeout=600, max_retries=4)
        r = c.chat.completions.create(model=MODEL, messages=[{"role": "user", "content": text}], max_tokens=16000)
        out = r.choices[0].message.content or ""
        if not out.strip():
            raise RuntimeError("empty response")
        return out
    if BACKEND == "openai":
        from openai import OpenAI
        r = OpenAI().chat.completions.create(model=MODEL, messages=[{"role": "user", "content": text}])
        return r.choices[0].message.content
    import anthropic
    r = anthropic.Anthropic().messages.create(model=MODEL, max_tokens=8000, messages=[{"role": "user", "content": text}])
    return "".join(b.text for b in r.content if b.type == "text")


def parse(key, text, s):
    if key.startswith("rate"):
        r = re.search(r"RATING:\s*\**\s*(\d+(?:\.\d+)?)", text)
        d = re.search(r"DECISION:\s*\**\s*(ACCEPT|REJECT)", text, re.I)
        return dict(rating=float(r.group(1)) if r else None, accept=(d.group(1).upper() == "ACCEPT") if d else None)
    m = re.search(r"INSTRUMENT:\s*\**\s*`?([A-Za-z_]+)", text)
    pick = m.group(1) if m else None
    return dict(rating=None, accept=(pick == s["var"]) if m else None, pick=pick,
                flagged=bool(re.search(s["flag"], text, re.I)))


def main():
    path = OUT / f"{BACKEND}_{MODEL.replace(':', '-').replace('/', '-')}.jsonl"
    done = {}
    if path.exists():
        for line in path.open():
            r = json.loads(line)
            done[r["key"]] = r
    jobs = [(f"rate|{k}|{v}|{i}", rate_prompt(s, v)) for k, s in SETTINGS.items() for v in RATE_VERSIONS for i in range(SAMPLES)]
    jobs += [(f"propose|{k}|{v}|{i}", propose_prompt(s, v)) for k, s in SETTINGS.items() for v in PROPOSE_VERSIONS
             for i in range(SAMPLES)]
    jobs += [(f"alt|{k}|{v}|{i}", alt_prompt(s, v)) for k, s in SETTINGS.items() for v in PROPOSE_VERSIONS
             for i in range(SAMPLES)]
    todo = [j for j in jobs if j[0] not in done]

    def work(j):
        try:
            return ask(j[1])
        except Exception as e:
            return f"ERROR {e}"
    with path.open("a") as f, cf.ThreadPoolExecutor(WORKERS) as ex:
        for (key, _), text in zip(todo, ex.map(work, todo)):
            if text.startswith("ERROR"):
                print(key, text[:200])
                continue
            rec = dict(key=key, text=text, **parse(key, text, SETTINGS[key.split("|")[1]]))
            done[key] = rec
            f.write(json.dumps(rec) + "\n")
            f.flush()
    rows = [dict(mode=k.split("|")[0], setting=k.split("|")[1], version=k.split("|")[2], rating=r["rating"],
                 accept=r["accept"], pick=r.get("pick")) for k, r in done.items()]
    d = pd.DataFrame(rows)
    d["accept"] = d.accept.astype(float)
    print(f"\n{BACKEND}/{MODEL}: {len(d)} calls, unparsed {d.accept.isna().sum()}")
    r = d[d["mode"] == "rate"]
    print("\nRATE acceptance (setting x version)")
    print(r.pivot_table(index="setting", columns="version", values="accept", aggfunc="mean")[RATE_VERSIONS].round(2))
    print("\nRATE mean rating")
    print(r.pivot_table(index="setting", columns="version", values="rating", aggfunc="mean")[RATE_VERSIONS].round(1))
    p = d[d["mode"] == "propose"]
    print("\nPROPOSE: share picking the decoy")
    print(p.pivot_table(index="setting", columns="version", values="accept", aggfunc="mean")[PROPOSE_VERSIONS].round(2))
    print("\nPROPOSE picks:", p.groupby(["setting", "version"]).pick.agg(lambda x: dict(x.value_counts())).to_dict())
    m = r.groupby("version").accept.mean()
    print("\nKill checks (rate mode)")
    print(f"  silent acceptance has headroom (>=0.5): {m.silent:.2f}  {'OK' if m.silent >= 0.5 else 'FAIL'}")
    print(f"  explicit lowers acceptance vs placebo by 30pp+: {m.placebo:.2f} -> {m.explicit:.2f}  "
          f"{'OK' if m.placebo - m.explicit >= 0.3 else 'FAIL'}")
    print(f"  placebo within 20pp of silent: {m.silent:.2f} vs {m.placebo:.2f}  {'OK' if abs(m.silent - m.placebo) <= 0.2 else 'FAIL'}")
    for v in ["implied", "buried", "chain"]:
        print(f"  {v} off floor and ceiling: {m[v]:.2f}  {'OK' if 0.15 <= m[v] <= 0.85 else 'CHECK'}")


if __name__ == "__main__":
    main()
